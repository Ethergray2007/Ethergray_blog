import type { Post } from "../data.ts";

/* ------------------------------------------------------------
 * 知识点 1：类型标注的基本写法
 *
 * 语法是 `属性名: 类型;`，注意是冒号，不是等号。
 * 分号可以省略，但加上更整齐。
 * ---------------------------------------------------------- */
export type Lesson01State = {
  text: string;
  count: number;
  isReady: boolean;
};

/* ------------------------------------------------------------
 * 知识点 2：函数签名
 *
 * 括号里是参数：`post: Post` 表示"参数 post 是 Post 类型"。
 * 括号后面是返回类型：`: string` 表示"这个函数一定返回字符串"。
 *
 * 如果把返回类型写成 number，TS 会立刻报错：
 *   类型 "string" 不能赋值给类型 "number"
 * 这就是类型检查在你写代码时就帮你抓错。
 * ---------------------------------------------------------- */
export function getPostTitle(post: Post): string {
  return post.title;
}

/* ------------------------------------------------------------
 * 知识点 3：模板字符串
 *
 * 反引号 ` 里可以用 ${} 插入任何表达式。
 *
 * 最容易踩的坑：getMonth() 返回 0~11！
 *   1 月是 0，12 月是 11，所以必须 +1。
 * （getDate() 是正常的 1~31，别搞混）
 * ---------------------------------------------------------- */
export function formatDate(date: Date): string {
  const year = date.getFullYear();
  const month = date.getMonth() + 1;
  const day = date.getDate();

  return `${year}年${month}月${day}日`;
}
