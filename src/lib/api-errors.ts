/**
 * API 的统一错误标识
 * ============================================================
 * 为什么要有这个文件：
 *   如果每个路由各写各的错误标识，前端就得猜"这次是什么字符串"。
 *   统一成一组常量，改名字时编译器会帮你找出所有引用点。
 *
 * 格式约定：所有接口出错都返回同样的形状
 *   { error: "给用户看的中文说明", code: "机器判断用的英文标识" }
 *
 * 为什么 error 用中文、code 用英文：
 *   error 是给人看的，中文说明比英文枚举有用。
 *   code 是给代码判断用的（比如 401 时前端跳登录页），英文更稳定。
 *
 * 想删掉？这个文件被 src/pages/api/_routes/index.ts 引用，
 * 删它之前先把那边的引用一起处理。
 * ============================================================
 */

/** 机器判断用的错误标识 */
export const API_ERROR = {
  /** 没登录，或登录已过期 */
  unauthorized: "UNAUTHORIZED",
  /** 请求的数据不合法 */
  badRequest: "BAD_REQUEST",
  /** 找不到资源 */
  notFound: "NOT_FOUND",
  /** 服务器内部出错 */
  internal: "INTERNAL",
  /** 路由不存在 */
  noRoute: "NO_ROUTE",
} as const;
