/**
 * 数据库连接的复用
 * ============================================================
 * 为什么需要这个文件，而不是在路由里直接 createDb()：
 *
 * Serverless 环境下，函数实例会被**复用**（热启动）。
 * 一次请求执行几次 getDb()，不缓存就会执行几次 createDb()，
 * 白白多出几次"新建客户端"的开销。
 * 所以这里缓存一个实例，整个实例生命周期内共用。
 *
 * ⚠️ 缓存的是 Drizzle 实例，**不是数据库连接**。
 *    驱动是 Neon HTTP 驱动（见 client.ts），每条查询各自发一个
 *    fetch 请求，本来就没有 TCP 连接和连接池需要维护 ——
 *    这个文件开的那个头曾经写的是"防止连接数用满"，那是换驱动
 *    （TCP → HTTP）之前的理由，现在不成立了。
 * ============================================================
 */
import { createDb, type Db } from "./client.ts";

let cached: Db | undefined;

/** 取得（或首次创建）数据库连接 */
export function getDb(): Db {
  cached ??= createDb();

  return cached;
}
