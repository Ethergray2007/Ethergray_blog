/**
 * 数据库连接的复用
 * ============================================================
 * 为什么需要这个文件，而不是在路由里直接 createDb()：
 *
 * Serverless 环境下，函数实例会被**复用**（热启动）。
 * 如果每个请求都新建一次连接，几十个请求就会把数据库的
 * 连接数用满（Neon 免费层连接数是有限的）。
 *
 * 所以这里缓存一个连接，整个实例生命周期内共用。
 * 实例被回收时连接自然断开，不需要我们操心。
 * ============================================================
 */
import { createDb, type Db } from "./client.ts";

let cached: Db | undefined;

/** 取得（或首次创建）数据库连接 */
export function getDb(): Db {
  cached ??= createDb();

  return cached;
}
